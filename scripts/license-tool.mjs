import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const KEYS_DIR = path.join(__dirname, '.keys');
const PRIVATE_KEY_PATH = path.join(KEYS_DIR, 'license_private.key');
const PUBLIC_KEY_MODULE_PATH = path.join(__dirname, '..', 'licensing', 'publicKey.js');

function ensureKeypair() {
  if (fs.existsSync(PRIVATE_KEY_PATH) && fs.existsSync(PUBLIC_KEY_MODULE_PATH)) {
    return;
  }

  if (!fs.existsSync(KEYS_DIR)) {
    fs.mkdirSync(KEYS_DIR, { recursive: true });
  }

  console.log('[*] Generating new Ed25519 master keypair...');
  const { privateKey, publicKey } = crypto.generateKeyPairSync('ed25519', {
    privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
    publicKeyEncoding: { type: 'spki', format: 'pem' }
  });

  fs.writeFileSync(PRIVATE_KEY_PATH, privateKey, { mode: 0o600 });

  const publicModuleContent = `// Auto-generated public key for license verification.
// DO NOT EDIT MANUALLY. Generated by scripts/license-tool.mjs.
export const PUBLIC_KEY_PEM = ${JSON.stringify(publicKey)};
`;
  fs.writeFileSync(PUBLIC_KEY_MODULE_PATH, publicModuleContent, 'utf-8');
  console.log('[+] Master keypair created successfully!');
  console.log('    Private key saved to: scripts/.keys/license_private.key (KEEP THIS SECRET!)');
  console.log('    Public key saved to: licensing/publicKey.js');
}

function getPrivateKey() {
  if (!fs.existsSync(PRIVATE_KEY_PATH)) {
    ensureKeypair();
  }
  return fs.readFileSync(PRIVATE_KEY_PATH, 'utf-8');
}

function parseArgs() {
  const args = process.argv.slice(2);
  const command = args[0] || 'help';
  const options = {};

  for (let i = 1; i < args.length; i++) {
    if (args[i].startsWith('--')) {
      const key = args[i].substring(2);
      const val = args[i + 1] && !args[i + 1].startsWith('--') ? args[++i] : true;
      options[key] = val;
    }
  }

  return { command, options };
}

function signLicense(payload, privateKeyPem) {
  const jsonStr = JSON.stringify(payload);
  const dataBuffer = Buffer.from(jsonStr, 'utf-8');
  const signature = crypto.sign(null, dataBuffer, privateKeyPem);

  const container = {
    p: payload,
    s: signature.toString('base64')
  };

  const containerStr = JSON.stringify(container);
  const base64License = Buffer.from(containerStr, 'utf-8').toString('base64');
  return `EMUNIM-LIC-${base64License}`;
}

function verifyLicense(licenseKey, publicKeyPem) {
  if (!licenseKey.startsWith('EMUNIM-LIC-')) {
    throw new Error('Invalid license format. Must start with EMUNIM-LIC-');
  }

  const rawBase64 = licenseKey.replace(/^EMUNIM-LIC-/, '').trim();
  const jsonStr = Buffer.from(rawBase64, 'base64').toString('utf-8');
  const container = JSON.parse(jsonStr);

  const payloadBuf = Buffer.from(JSON.stringify(container.p), 'utf-8');
  const sigBuf = Buffer.from(container.s, 'base64');

  const isValid = crypto.verify(null, payloadBuf, publicKeyPem, sigBuf);
  return { isValid, payload: container.p };
}

function printHelp() {
  console.log(`
=============================================================
E-Munim License Generator CLI
=============================================================
Usage:
  node scripts/license-tool.mjs init-keys
    Generates developer private key and embeds public key.

  node scripts/license-tool.mjs generate --hwid <HWID> [options]
    Generates a cryptographically signed license key.
    Options:
      --hwid <XXXX-XXXX-XXXX-XXXX>   Customer's Machine ID (Required)
      --type <trial|lifetime>        License type (default: trial if --days is specified)
      --days <number>                Number of trial days (e.g. 7)
      --name <name>                  Customer name or phone (optional)

  node scripts/license-tool.mjs verify --key <LICENSE_KEY>
    Verifies a license key and displays its details.

Examples:
  # Generate 7-day Demo Key:
  node scripts/license-tool.mjs generate --hwid B17E-D3EF-FD24-9A44 --days 7 --name "Aman"

  # Generate Lifetime / Permanent Key:
  node scripts/license-tool.mjs generate --hwid B17E-D3EF-FD24-9A44 --type lifetime --name "Aman"
=============================================================
`);
}

async function main() {
  const { command, options } = parseArgs();

  if (command === 'init-keys') {
    ensureKeypair();
    return;
  }

  if (command === 'generate') {
    if (!options.hwid) {
      console.error('Error: --hwid is required! Example: --hwid B17E-D3EF-FD24-9A44');
      process.exit(1);
    }

    ensureKeypair();
    const privateKey = getPrivateKey();

    const hwid = options.hwid.trim().toUpperCase();
    const isLifetime = options.type === 'lifetime' || (!options.days && options.type !== 'trial');
    const trialDays = options.days ? parseInt(options.days, 10) : 7;

    const now = new Date();
    let expiresAt = null;

    if (!isLifetime) {
      const expDate = new Date(now.getTime() + trialDays * 24 * 60 * 60 * 1000);
      expiresAt = expDate.toISOString();
    }

    const payload = {
      v: 1,
      hwid,
      type: isLifetime ? 'LIFETIME' : 'TRIAL',
      issuedAt: now.toISOString(),
      expiresAt: expiresAt,
      name: options.name || 'Valued Customer',
      features: ['all']
    };

    const licenseKey = signLicense(payload, privateKey);

    console.log('\n=============================================================');
    console.log(`LICENSE KEY GENERATED (${payload.type})`);
    console.log('=============================================================');
    console.log(`Customer:   ${payload.name}`);
    console.log(`Machine ID: ${payload.hwid}`);
    console.log(`Type:       ${payload.type}`);
    console.log(`Issued:     ${payload.issuedAt}`);
    console.log(`Expires:    ${payload.expiresAt || 'NEVER (Lifetime)'}`);
    console.log('-------------------------------------------------------------');
    console.log('Copy the license key below to send to customer:\n');
    console.log(licenseKey);
    console.log('\n=============================================================\n');
    return;
  }

  if (command === 'verify') {
    if (!options.key) {
      console.error('Error: --key is required! Example: --key EMUNIM-LIC-...');
      process.exit(1);
    }

    const { PUBLIC_KEY_PEM } = await import('../licensing/publicKey.js');
    try {
      const result = verifyLicense(options.key, PUBLIC_KEY_PEM);
      console.log('\nVerification result:', result.isValid ? 'VALID' : 'INVALID');
      console.log('Payload:', JSON.stringify(result.payload, null, 2));
    } catch (err) {
      console.error('Verification failed:', err.message);
    }
    return;
  }

  printHelp();
}

main().catch(err => {
  console.error('Fatal error:', err);
  process.exit(1);
});
